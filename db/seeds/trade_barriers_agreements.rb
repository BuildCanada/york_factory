  theme = attrs[:theme] ? TradeBarriers::Theme.find_by!(name: attrs[:theme]) : nil
  agreement = TradeBarriers::Agreement.find_or_initialize_by(title: attrs[:title])
  agreement.assign_attributes(
    status:      attrs[:status],
    summary:     attrs[:summary],
    description: attrs[:description],
    deadline:    attrs[:deadline],
    launch_date: attrs[:launch_date],
    source_url:  attrs[:source_url],
    theme:       theme
  )
  agreement.save!

  agreement.agreement_jurisdictions.destroy_all
  attrs[:jurisdictions].each do |j|
    jurisdiction = Warehouse::Jurisdiction.find_by!(name: j[:name])
    agreement.agreement_jurisdictions.create!(jurisdiction: jurisdiction, status: j[:status], notes: j[:notes])
  end

  agreement.histories.delete_all
  attrs[:history].each do |h|
    agreement.histories.create!(status: h[:status], date_entered: h[:date_entered])
  end
end

